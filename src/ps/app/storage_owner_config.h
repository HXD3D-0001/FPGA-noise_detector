#ifndef LFN_STORAGE_OWNER_CONFIG_H
#define LFN_STORAGE_OWNER_CONFIG_H
/* One value for every translation unit in an image. Legacy auxiliary images
 * retain two files; the production capture build explicitly selects four. */
#ifndef LFN_STORAGE_OWNER_FILES
#define LFN_STORAGE_OWNER_FILES 2
#endif
#if LFN_STORAGE_OWNER_FILES != 2 && LFN_STORAGE_OWNER_FILES != 4
#error LFN_STORAGE_OWNER_FILES must be 2 or 4
#endif
enum {
 STORAGE_OWNER_MONITOR=0,STORAGE_OWNER_PSD=1,
 STORAGE_OWNER_SUMMARY=2,STORAGE_OWNER_EVENT=3,
 STORAGE_OWNER_FILES=LFN_STORAGE_OWNER_FILES,
 STORAGE_OWNER_GROUPS=2,
 STORAGE_OWNER_GROUP_FILES=STORAGE_OWNER_FILES+2,
 STORAGE_OWNER_HANDLES=STORAGE_OWNER_GROUPS*STORAGE_OWNER_GROUP_FILES
};
#endif
